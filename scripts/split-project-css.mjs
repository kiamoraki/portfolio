#!/usr/bin/env node
/**
 * One-shot CSS splitter — extracts every per-project rule from
 * `app/globals.css` into `app/project-page.css`. Per-project markers:
 *   - `data-project-slug=`
 *   - `data-slug=`
 *   - `data-slug^=`
 *   - `data-piece-id=`
 *   - `data-meta-active-slug=`
 *
 * Uses postcss (already a devDependency) to walk the AST so we don't
 * have to hand-roll a CSS parser. Preserves @media context — if an
 * @media block contains a mix, the per-project rules are wrapped in
 * an equivalent @media block in the output file.
 *
 * Output:
 *   - rewrites app/globals.css with per-project rules removed
 *   - writes app/project-page.css with the extracted rules
 *
 * Run once, then `/projects/[slug]/page.tsx` imports project-page.css
 * directly.
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import postcss from "postcss";

const ROOT = path.resolve("app");
const GLOBALS = path.join(ROOT, "globals.css");
const PROJECT_PAGE = path.join(ROOT, "project-page.css");

const PROJ_RE = /data-project-slug|data-slug|data-piece-id|data-meta-active-slug/;

function isProjectSelector(selector) {
  return PROJ_RE.test(selector || "");
}

async function main() {
  const src = await fs.readFile(GLOBALS, "utf8");
  const root = postcss.parse(src);

  // Build the project root by cloning + filtering.
  const projectRoot = postcss.root();

  // Walk the original root's children. Collect rules to move + remove
  // them from globals. Preserve @media context.
  const toRemove = [];
  for (const node of root.nodes) {
    if (node.type === "rule") {
      if (isProjectSelector(node.selector)) {
        projectRoot.append(node.clone());
        toRemove.push(node);
      }
    } else if (node.type === "atrule" && node.name === "media") {
      // Walk the media's children; split.
      const moveable = [];
      const stay = [];
      for (const inner of node.nodes || []) {
        if (inner.type === "rule" && isProjectSelector(inner.selector)) {
          moveable.push(inner);
        } else {
          stay.push(inner);
        }
      }
      if (moveable.length) {
        const newMedia = node.clone({ nodes: [] });
        for (const m of moveable) newMedia.append(m.clone());
        projectRoot.append(newMedia);
        // Remove from original
        for (const m of moveable) m.remove();
        // If the original media is now empty, remove the wrapper too
        if ((node.nodes || []).length === 0) toRemove.push(node);
      }
    }
    // @font-face, @keyframes, comments, etc. — leave alone in globals.
  }
  for (const n of toRemove) n.remove();

  const newGlobals = root.toString();
  const projectHeader = [
    "/*",
    " * project-page.css — per-project rules extracted from globals.css.",
    " *",
    " * Generated by scripts/split-project-css.mjs (one-shot). Only",
    " * imported by app/projects/[slug]/page.tsx, so routes that don't",
    " * render a single project (homepage, /about, /projects/animations",
    " * meta page) skip this chunk entirely.",
    " *",
    " * Per-project selector markers extracted:",
    " *   data-project-slug=, data-slug=, data-piece-id=,",
    " *   data-meta-active-slug=",
    " *",
    " * Edit by hand from here on — the split script is one-shot.",
    " */",
    "",
  ].join("\n");
  const newProject = projectHeader + projectRoot.toString();

  await fs.writeFile(GLOBALS, newGlobals);
  await fs.writeFile(PROJECT_PAGE, newProject);

  console.log(`globals.css:      ${newGlobals.length} bytes`);
  console.log(`project-page.css: ${newProject.length} bytes`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
